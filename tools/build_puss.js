// Builds public/engines/puss.js from the PuSS-30 NWB slot source (puss30.html, UI v28).
// Every DSP/FX/bank segment is sliced VERBATIM from the source; only the wrapper below is new.
const fs=require('fs'),path=require('path');
const SRC=process.argv[2], OUT=process.argv[3];
const s=fs.readFileSync(SRC,'utf8');
function block(startToken){ // from startToken through matching closing brace/bracket of the first { or [ after it
  const i=s.indexOf(startToken); if(i<0) throw Error('missing '+startToken);
  let j=i+startToken.length; while(s[j]!=='{'&&s[j]!=='[') j++;
  const open=s[j],close=open==='{'?'}':']'; let d=0,k=j,inStr=null;
  for(;k<s.length;k++){const c=s[k];
    if(inStr){ if(c==='\\'){k++;continue} if(c===inStr) inStr=null; continue }
    if(c==="'"||c==='"'||c==='`'){inStr=c;continue}
    if(c===open) d++; else if(c===close){d--; if(!d) break}}
  return s.slice(i,k+1);
}
function line(startToken){const i=s.indexOf(startToken);if(i<0)throw Error('missing '+startToken);return s.slice(i,s.indexOf(';',i)+1)}
const wi=s.indexOf('const WORKLET=`'); const we=s.indexOf('`;',wi+15);
const WORKLET=s.slice(wi+'const WORKLET=`'.length,we);
const parts=[
  block('const CORE='),
  block('const PROGRAMS='),
  line('const CAT_ORDER='),
  block('const FACTORY_CAT='),
  block('const BASE_SYNTH='),
  line('const VOL_STEPS='),
  block('function volumeGain(step)'),
  block('function makeCurve('),
  block('function buildChain('),
  block('function applyFxTo('),
  block('const macroDefs='),
];
const ver=(s.match(/UI_VERSION='(\d+)'/)||[])[1];
let out=`// PuSS-30 engine for Loopkiste. GENERATED by tools/build_puss.js from puss30.html (UI v${ver}).
// DSP worklet, factory bank, FX chain and macros are verbatim copies of the instrument source.
const WORKLET=${JSON.stringify(WORKLET)};
const clamp01=v=>Math.max(0,Math.min(1,v));
${parts.join(';\n')};
`;
out+=fs.readFileSync(path.join(__dirname,'puss_wrapper.js'),'utf8');
fs.writeFileSync(OUT,out);
console.log('segments ok, worklet chars',WORKLET.length);
